/**
 * Fail fast when this worktree has no local node_modules.
 *
 * Interactive a11y fixtures load Alpine and htmx by relative path from the
 * fixture directory into THIS tree's node_modules. `npx playwright` can still
 * resolve up the directory tree from a parent checkout, so a missing install
 * looks like 100+ uniform 30s timeouts instead of a missing dependency
 * (icvoss/django-brickwork#336).
 */
import { existsSync } from "node:fs";
import { join } from "node:path";

export const MISSING_NODE_MODULES_MESSAGE =
  "node_modules/alpinejs is missing in this worktree. Run `npm ci` here before `npx playwright test` or `npm run a11y` (icvoss/django-brickwork#336).";

/**
 * @param {string} repoRoot Absolute path to the repo / worktree root.
 * @returns {string | null} Error message when the marker package is absent, else null.
 */
export function missingNodeModulesMessage(repoRoot) {
  const alpineMarker = join(repoRoot, "node_modules", "alpinejs");
  if (existsSync(alpineMarker)) {
    return null;
  }
  return MISSING_NODE_MODULES_MESSAGE;
}

/**
 * @param {string} repoRoot Absolute path to the repo / worktree root.
 */
export function assertLocalNodeModules(repoRoot) {
  const message = missingNodeModulesMessage(repoRoot);
  if (message !== null) {
    throw new Error(message);
  }
}
